"""Truth-assisted single-query controls for saved receiver pseudo-observations."""
import os
for key in ('OMP_NUM_THREADS','OPENBLAS_NUM_THREADS','MKL_NUM_THREADS'):
    os.environ[key]='1'
import argparse
from pathlib import Path
import numpy as np
import torch
from scipy.special import expit, logit
from threadpoolctl import threadpool_limits
import evaluate_saved_baseline_inputs as paired
from benchmark_receiver_execution import GraphForward


def run(condition, iteration, scene):
    root=paired.ROOT/'results/user_count_stability_20261019'
    source=root/'query_prefixes'/f'scene{scene:03d}_users{20*(condition+1)}'/f'iteration{iteration:03d}.npz'
    output=root/f'queries_scene{scene:03d}_users{20*(condition+1)}_iteration{iteration:03d}'
    if output.exists():
        raise ValueError('Fresh diagnostic output required')
    plan=paired.read(paired.ROOT/'results/new_models_paired_20261019_v2/user_count/PLAN.json')
    paired.verify_sources(plan)
    baseline=Path(plan['baseline_results'])/f'scene{scene:03d}'/f'condition{condition:02d}'
    truth=paired.arrays(baseline/'truth.npz'); public=paired.arrays(baseline/'public.npz')
    config=plan['experiment']['proposed_bundles']['proposed']['configuration']
    model=paired.EstimatedNoiseProposedReceiver(config,device='cuda').base
    model.model.first=GraphForward(model.model.first);model.model.second=GraphForward(model.model.second)
    torch.set_num_threads(1)
    if not source.exists():
        if iteration != 1:
            raise ValueError('Only one-iteration prefixes are generated by this diagnostic')
        index=paired.read(Path(plan['input_package'])/'inputs/INDEX.json')['experiments']['user_count']['cases']
        inputs,_,hashes,_,_,_=paired.load_case(plan,index,scene,condition)
        receiver=paired.EstimatedNoiseProposedReceiver(config,device='cuda')
        receiver.base=model
        class PrefixSaved(Exception):
            pass
        def save_prefix(row,state,query,covariance,*unused):
            assert row['iteration']==1
            paired.save_arrays(source,dict(query=query,covariance=covariance))
            paired.save(source.with_suffix('.json'),dict(status='DIAGNOSTIC_PREFIX_ONLY',iterations=1,input_sha256=hashes,truth_used_in_inference=False))
            raise PrefixSaved()
        with threadpool_limits(1):
            try:
                receiver.infer(inputs,observer=save_prefix)
            except PrefixSaved:
                pass
    snapshot=paired.arrays(source)
    target=truth['channel']/config['scale'];active=truth['activity'].astype(bool)
    actual=snapshot['query'];variance=float(np.trace(snapshot['covariance']).real/16)
    error=actual-target;packed=error.transpose(1,0,2,3).reshape(16,-1)
    covariance=packed@packed.conj().T/packed.shape[1]
    covariance=covariance*(16*variance/np.trace(covariance).real)
    eigen,basis=np.linalg.eigh(covariance)
    if eigen[0]<-1e-10*eigen[-1]:
        raise ValueError('Empirical error covariance is not positive semidefinite')
    factor=basis*np.sqrt(np.maximum(eigen,0))
    prior=float(public['activity_prior']);energy=float(np.sum(abs(target)**2))
    rows=[]
    def evaluate(kind,query,seed):
        moments=model.model.infer(query,np.full(len(query),variance))
        logits=model.evidence.infer(query,np.full(len(query),variance),moments.mean)
        probability=expit(logit(prior)+logits)
        estimate=probability[:,None,None,None]*moments.mean
        row=dict(kind=kind,seed=seed,query_sha256=paired.array_sha256(query),variance=variance,
            actual_error_to_label=float(np.mean(abs(query-target)**2)/variance),
            joint_nmse_db=float(10*np.log10(np.sum(abs(estimate-target)**2)/energy)),
            active_conditional_nmse_db=float(10*np.log10(np.sum(abs(moments.mean[active]-target[active])**2)/energy)),
            misses=int(np.count_nonzero((probability<.5)&active)),
            false_alarms=int(np.count_nonzero((probability>=.5)&~active)),
            active_probability=float(probability[active].mean()),inactive_probability=float(probability[~active].mean()),
            active_predicted_variance=float(moments.variance[active].mean()))
        rows.append(row)
    with threadpool_limits(1):
        evaluate('actual_receiver_query',actual,None)
        for repeat in range(3):
            seed=202610190900001+repeat
            rng=np.random.default_rng(seed)
            white=(rng.normal(size=target.shape)+1j*rng.normal(size=target.shape))/np.sqrt(2)
            evaluate('independent_white_gaussian',target+np.sqrt(variance)*white,seed)
            diagonal=np.sqrt(np.diag(covariance).real)[None,:,None,None]*white
            evaluate('independent_gaussian_matching_antenna_powers',target+diagonal,seed)
            correlated=np.einsum('mn,knrc->kmrc',factor,white,optimize=False)
            evaluate('gaussian_matching_antenna_covariance',target+correlated,seed)
    report=dict(scope='Truth-assisted single-query diagnosis, not deployable receiver results or population estimates',
        source=str(source),source_sha256=paired.sha(source),truth_used_to_construct_queries=True,
        variance=variance,active_users=int(active.sum()),inactive_users=int((~active).sum()),
        eigen_fraction_largest=float(eigen[-1]/eigen.sum()),
        equal_expected_total_variance=True,rows=rows,
        source_and_weight_sha256=plan['source_and_weight_sha256']|{str(Path(__file__)):paired.sha(Path(__file__))})
    paired.save(output/'REPORT.json',report)
    print({'iteration':iteration,'variance':variance,'eigen_fraction_largest':report['eigen_fraction_largest']},flush=True)
    for row in rows:print(row,flush=True)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--condition',type=int,default=2)
    parser.add_argument('--iteration',type=int,default=1)
    parser.add_argument('--scene',type=int,required=True)
    args=parser.parse_args();run(args.condition,args.iteration,args.scene)
